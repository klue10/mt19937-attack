import os, random, secrets, time
import streamlit as st
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes

# ---------------------------------------------------------------- attack core
def untemper(y):
    """Invert the MT19937 tempering function (4 reversible steps)."""
    y ^= y >> 18
    y ^= (y << 15) & 0xEFC60000
    # undo y ^= (y << 7) & 0x9D2C5680  (iterate to fix 7 bits at a time)
    t = y
    for _ in range(5):
        t = y ^ ((t << 7) & 0x9D2C5680)
    y = t & 0xFFFFFFFF
    # undo y ^= y >> 11
    t = y
    for _ in range(3):
        t = y ^ (t >> 11)
    return t & 0xFFFFFFFF

def clone_rng(outputs):
    """Rebuild a Python Random object from 624 consecutive 32-bit outputs."""
    assert len(outputs) >= 624
    state = [untemper(o) for o in outputs[:624]]
    r = random.Random()
    r.setstate((3, tuple(state + [624]), None))  # index 624 -> twist on next call
    return r

def aes_ctr(key: bytes, data: bytes, nonce: bytes) -> bytes:
    c = Cipher(algorithms.AES(key), modes.CTR(nonce)).encryptor()
    return c.update(data) + c.finalize()

# ---------------------------------------------------------------- UI
st.set_page_config(page_title="Weak RNG Attack", page_icon="🎲", layout="wide")
st.sidebar.title("🎲 Weak RNG Attack")
role = st.sidebar.radio("Role", ["Victim", "Attacker"])
mode = st.sidebar.radio("Victim's generator",
                        ["random (MT19937) - weak", "secrets (OS CSPRNG) - fixed"])
st.sidebar.caption("Victim generates. Attacker sees only public data.")
weak = mode.startswith("random")

st.title("Breaking MT19937: from 624 outputs to the secret key")
st.caption("SC4010 Project B - period 2^19937, yet totally predictable.")

if role == "Victim":
    st.subheader("Victim - web service leaking session tokens")
    secret = st.text_input("Secret file contents", "GOOD !")
    if st.button("Run service & encrypt"):
        if weak:
            rng = random.Random(secrets.randbits(64))      # unknown seed
            tokens = [rng.getrandbits(32) for _ in range(624)]
            aes_key = rng.getrandbits(128).to_bytes(16, "big")  # key from SAME rng
        else:
            tokens = [secrets.randbits(32) for _ in range(624)]
            aes_key = secrets.token_bytes(16)
        nonce = os.urandom(16)
        ct = aes_ctr(aes_key, secret.encode(), nonce)
        st.session_state.update(tokens=tokens, nonce=nonce, ct=ct,
                                aes_key=aes_key, weak=weak, secret=secret)
    if "tokens" in st.session_state:
        s = st.session_state
        st.success("624 session tokens were published; then an AES-128 key was "
                   "generated by the same generator and the file encrypted.")
        st.markdown("**Public (attacker sees this):**")
        st.code(f"tokens[0..2] = {s['tokens'][:3]} ... (624 total)\n"
                f"nonce        = {s['nonce'].hex()}\n"
                f"AES ciphertext = {s['ct'].hex()}")
        st.markdown("**Private (hidden):** AES key = " + f"`{s['aes_key'].hex()}`")
else:
    st.subheader("Attacker - state recovery + key prediction")
    if "tokens" not in st.session_state:
        st.info("Run the Victim first.")
    else:
        s = st.session_state
        st.code(f"{len(s['tokens'])} tokens observed, e.g. {s['tokens'][:2]}")
        if st.button("Run MT19937 attack"):
            t0 = time.perf_counter()
            clone = clone_rng(s["tokens"])
            # sanity check: does the clone reproduce a few outputs? (consumes 4 words)
            guess = clone.getrandbits(128).to_bytes(16, "big")
            ms = (time.perf_counter() - t0) * 1000
            plain = aes_ctr(guess, s["ct"], s["nonce"])
            ok = guess == s["aes_key"]
            (st.success if ok else st.error)(
                f"{'Recovered' if ok else 'FAILED to recover'} the AES key in {ms:.2f} ms.")
            st.code(f"AES key (predicted) = {guess.hex()}")
            st.markdown("**Decrypted file:**")
            st.code(plain.decode(errors="replace"))
            st.caption(f"Matches victim's secret key: {ok}")
            if not ok:
                st.warning("Expected: the OS CSPRNG has no recoverable state.")

with st.expander("How it works / why it's fixed (for Q&A)"):
    st.markdown("""
- MT19937 state = 624 x 32-bit words. Each output is the state word passed through
  an **invertible** tempering function, so 624 outputs reveal the whole state.
- We untemper each output, load the state, and every future output is predicted.
- **Fix:** use a CSPRNG (`secrets`, `os.urandom`, ChaCha20/DRBG). MT is linear over GF(2);
  CSPRNGs are built on one-way/PRF primitives.
""")
